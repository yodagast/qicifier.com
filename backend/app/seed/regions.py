def all_regions() -> list[dict]:
    """Flat list of province / city / district / town rows (level annotated)."""
    rows: list[dict] = [
        {"code": "330000", "name": "浙江省", "level": "province", "parent_code": None}
    ]
    for code, name in CITIES:
        rows.append({"code": code, "name": name, "level": "city", "parent_code": "330000"})
    for city_code, items in DISTRICTS.items():
        for code, name in items:
            rows.append({"code": code, "name": name, "level": "district", "parent_code": city_code})
    for code, name, district_code in TOWNS:
        rows.append({"code": code, "name": name, "level": "town", "parent_code": district_code})
    for code, name, city_code in ZONES:
        rows.append({"code": code, "name": name, "level": "district", "parent_code": city_code})
    return rows


def district_count() -> int:
    return sum(len(v) for v in DISTRICTS.values())